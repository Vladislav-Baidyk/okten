/*
– У змінній day дано якесь число від 1 до 31. 
Потрібно визначити, у яку половину (декаду) місяця 
потрапляє це число (у першу, другу чи третю).
 */
let day =  Math.floor(Math.random() * 30 + 1);
console.log(day);
let check = day <= 10 
    ? 'Перша декада' 
    : day <= 20 
        ? 'Друга декада' 
        : 'Третя декада';

console.log(check);